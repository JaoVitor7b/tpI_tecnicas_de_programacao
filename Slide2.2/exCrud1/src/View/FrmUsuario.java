    public void consultar(){
        ResultSet tabela;
        tabela = null;
        
        //CHAMAR O MÉTODO CONSULTAR
        tabela = usu.consultar();

        DefaultTableModel modelo = (DefaultTableModel) tblUsuario.getModel();
        modelo.setNumRows(0);

        try{
            if (tabela != null && !tabela.isAfterLast()) {
                do{
                    modelo.addRow(new String[] {
                        tabela.getString(1),
                        tabela.getString(2),
                        tabela.getString(3),
                        tabela.getString(4)
                    });
                }
                while(tabela.next());
            }
        }
        catch(SQLException erro){
            JOptionPane.showMessageDialog(null,"Erro preencher tabela: " + erro.getMessage());
        }
    }
